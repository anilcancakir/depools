#!/usr/bin/env python3
"""Check every colour pair in DESIGN.md against WCAG AA.

Runs before `design:lint` exists (that is generated by the magic_example fork) and
checks more pairs than it will: design:lint only covers `on-X`/`X`, while this also
covers text on every surface, accents used as text, and the Depools status family.

Exemptions are deliberate and sourced, not convenience:
  - Disabled states: WCAG 1.4.3 and 1.4.11 both exclude inactive components. A disabled
    control is low contrast on purpose, that is how it reads as disabled.
  - Hairline borders: 1.4.11 applies to UI components and meaningful graphics, not a
    decorative separator whose boundary is already carried by the surface fill. Apple's
    own `separator` at 29% opacity would fail a 3:1 test too.

Usage: python3 bin/verify-design-contrast.py
Exit 0 if every non-exempt pair passes.
"""

import re
import sys
from pathlib import Path

DESIGN = Path(__file__).resolve().parent.parent / 'DESIGN.md'


def parse_colors(text: str) -> dict[str, dict[str, str]]:
    frontmatter = text.split('---')[1]
    colors: dict[str, dict[str, str]] = {}
    token = None
    inside = False
    for line in frontmatter.splitlines():
        if re.match(r'^colors:', line):
            inside = True
            continue
        if inside and re.match(r'^\w', line):
            break
        if not inside:
            continue
        if m := re.match(r'^  ([\w-]+):\s*$', line):
            token = m.group(1)
            colors[token] = {}
        elif token and (m := re.match(r'^    (light|dark):\s*"(#[0-9A-Fa-f]{6})"', line)):
            colors[token][m.group(1)] = m.group(2)
    return colors


def luminance(hex_color: str) -> float:
    h = hex_color.lstrip('#')
    channels = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    channels = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * channels[0] + 0.7152 * channels[1] + 0.0722 * channels[2]


def contrast(a: str, b: str) -> float:
    la, lb = luminance(a), luminance(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)


# (foreground token, background token, required ratio, note). 0 means exempt, reported only.
PAIRS = [
    ('on-primary', 'primary', 4.5, 'design:lint gate'),
    ('on-destructive', 'destructive', 4.5, 'design:lint gate'),
    ('fg', 'surface', 4.5, 'body text on canvas'),
    ('fg', 'surface-container', 4.5, 'body text on card'),
    ('fg', 'surface-container-high', 4.5, 'body text on input'),
    ('fg-muted', 'surface', 4.5, 'secondary text on canvas'),
    ('fg-muted', 'surface-container', 4.5, 'secondary text on card'),
    ('fg', 'primary-container', 4.5, 'text on tinted block'),
    ('fg', 'destructive-container', 4.5, 'text on tinted block'),
    ('primary', 'surface', 3.0, 'accent as UI element'),
    ('primary', 'surface-container', 3.0, 'accent on card'),
    ('accent', 'surface-container', 4.5, 'accent as text'),
    ('success', 'surface-container', 4.5, 'status text on card'),
    ('warning', 'surface-container', 4.5, 'status text on card'),
    ('destructive', 'surface-container', 4.5, 'status text on card'),
    ('fg-disabled', 'surface-container', 0, 'EXEMPT: inactive component'),
    ('border', 'surface-container', 0, 'EXEMPT: decorative hairline'),
]

STATUS_TOKENS = Path(__file__).resolve().parent.parent / 'lib/config/depools_status_tokens.dart'


def parse_status() -> dict[str, dict[str, tuple[str, str]]]:
    """Read the status supplement so it is checked from its real source.

    Returns {family: {role: (light, dark)}} where role is 'solid', 'soft' or
    'soft-foreground'.
    """
    families: dict[str, dict[str, tuple[str, str]]] = {}
    pattern = re.compile(
        r"^\s*'(?:bg|text)-([a-z-]+?)(-soft-foreground|-soft)?':\s*"
        r"'(?:bg|text)-\[(#[0-9A-Fa-f]{6})\]\s+dark:(?:bg|text)-\[(#[0-9A-Fa-f]{6})\]'"
    )
    for line in STATUS_TOKENS.read_text().splitlines():
        if not (m := pattern.match(line)):
            continue
        family, suffix, light, dark = m.groups()
        role = {None: 'solid', '-soft': 'soft', '-soft-foreground': 'soft-foreground'}[suffix]
        families.setdefault(family, {})[role] = (light, dark)
    return families


def main() -> int:
    colors = parse_colors(DESIGN.read_text())
    failures: list[str] = []

    print(f"{'PAIR':<44}{'LIGHT':>8}{'':>4}{'DARK':>8}{'':>4}{'NEED':>6}")
    print('-' * 78)
    for fg, bg, need, note in PAIRS:
        if fg not in colors or bg not in colors:
            failures.append(f'missing token: {fg} or {bg}')
            continue
        rl = contrast(colors[fg]['light'], colors[bg]['light'])
        rd = contrast(colors[fg]['dark'], colors[bg]['dark'])
        if need == 0:
            mark_l = mark_d = ' exempt'
        else:
            mark_l = '   OK' if rl >= need else '  FAIL'
            mark_d = '   OK' if rd >= need else '  FAIL'
            if rl < need:
                failures.append(f'{fg}/{bg} light {rl:.2f} < {need}')
            if rd < need:
                failures.append(f'{fg}/{bg} dark {rd:.2f} < {need}')
        label = f'{fg} / {bg}'
        print(f'{label:<44}{rl:>8.2f}{mark_l:>4}{rd:>8.2f}{mark_d:>4}{need if need else "-":>6}')

    status = parse_status()

    print()
    print(f'STATUS SOLIDS on surface-container ({len(status)} families, parsed from '
          f'{STATUS_TOKENS.name})')
    print('-' * 78)
    for name, roles in status.items():
        light, dark = roles['solid']
        rl = contrast(light, colors['surface-container']['light'])
        rd = contrast(dark, colors['surface-container']['dark'])
        if rl < 4.5:
            failures.append(f'status {name} solid light {rl:.2f} < 4.5')
        if rd < 4.5:
            failures.append(f'status {name} solid dark {rd:.2f} < 4.5')
        print(f'{name:<44}{rl:>8.2f}{"   OK" if rl >= 4.5 else "  FAIL":>4}'
              f'{rd:>8.2f}{"   OK" if rd >= 4.5 else "  FAIL":>4}{4.5:>6}')

    print()
    print('STATUS BADGES: soft-foreground on its own soft background')
    print('-' * 78)
    for name, roles in status.items():
        if 'soft' not in roles or 'soft-foreground' not in roles:
            failures.append(f'status {name} is missing a soft or soft-foreground token')
            continue
        fg_l, fg_d = roles['soft-foreground']
        bg_l, bg_d = roles['soft']
        rl, rd = contrast(fg_l, bg_l), contrast(fg_d, bg_d)
        if rl < 4.5:
            failures.append(f'badge {name} light {rl:.2f} < 4.5')
        if rd < 4.5:
            failures.append(f'badge {name} dark {rd:.2f} < 4.5')
        print(f'{name + " badge":<44}{rl:>8.2f}{"   OK" if rl >= 4.5 else "  FAIL":>4}'
              f'{rd:>8.2f}{"   OK" if rd >= 4.5 else "  FAIL":>4}{4.5:>6}')

    print()
    if failures:
        print(f'{len(failures)} FAILURE(S):')
        for f in failures:
            print(f'  {f}')
        return 1
    print('All non-exempt pairs pass WCAG AA in both light and dark.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
