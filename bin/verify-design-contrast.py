#!/usr/bin/env python3
"""Check every colour pair in DESIGN.md against WCAG AA.

Runs before `design:lint` exists (that is generated by the magic_example fork) and
checks more pairs than it will: design:lint only covers `on-X`/`X`, while this also
covers text on every surface, accents used as text, and the Depools status family.

Exemptions are deliberate and sourced, not convenience:
  - Disabled states: WCAG 1.4.3 and 1.4.11 both exclude inactive components. A disabled
    control is low contrast on purpose, that is how it reads as disabled.
  - Hairline borders: 1.4.11 applies to UI components and meaningful graphics, not a
    decorative separator whose boundary is already carried by the surface fill. Apple's
    own `separator` at 29% opacity would fail a 3:1 test too.

Usage: python3 bin/verify-design-contrast.py
Exit 0 if every non-exempt pair passes.
"""

import itertools
import math
import re
import sys
from pathlib import Path

DESIGN = Path(__file__).resolve().parent.parent / 'DESIGN.md'


def parse_colors(text: str) -> dict[str, dict[str, str]]:
    frontmatter = text.split('---')[1]
    colors: dict[str, dict[str, str]] = {}
    token = None
    inside = False
    for line in frontmatter.splitlines():
        if re.match(r'^colors:', line):
            inside = True
            continue
        if inside and re.match(r'^\w', line):
            break
        if not inside:
            continue
        if m := re.match(r'^  ([\w-]+):\s*$', line):
            token = m.group(1)
            colors[token] = {}
        elif token and (m := re.match(r'^    (light|dark):\s*"(#[0-9A-Fa-f]{6})"', line)):
            colors[token][m.group(1)] = m.group(2)
    return colors


def luminance(hex_color: str) -> float:
    h = hex_color.lstrip('#')
    channels = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    channels = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * channels[0] + 0.7152 * channels[1] + 0.0722 * channels[2]


def contrast(a: str, b: str) -> float:
    la, lb = luminance(a), luminance(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)


# (foreground token, background token, required ratio, note). 0 means exempt, reported only.
PAIRS = [
    ('on-primary', 'primary', 4.5, 'design:lint gate'),
    ('on-destructive', 'destructive', 4.5, 'design:lint gate'),
    ('fg', 'surface', 4.5, 'body text on canvas'),
    ('fg', 'surface-container', 4.5, 'body text on card'),
    ('fg', 'surface-container-high', 4.5, 'body text on input'),
    ('fg-muted', 'surface', 4.5, 'secondary text on canvas'),
    ('fg-muted', 'surface-container', 4.5, 'secondary text on card'),
    ('fg', 'primary-container', 4.5, 'text on tinted block'),
    ('fg', 'destructive-container', 4.5, 'text on tinted block'),
    ('primary', 'surface', 3.0, 'accent as UI element'),
    ('primary', 'surface-container', 3.0, 'accent on card'),
    ('accent', 'surface-container', 4.5, 'accent as text'),
    ('success', 'surface-container', 4.5, 'status text on card'),
    ('warning', 'surface-container', 4.5, 'status text on card'),
    ('destructive', 'surface-container', 4.5, 'status text on card'),
    ('fg-disabled', 'surface-container', 0, 'EXEMPT: inactive component'),
    ('border', 'surface-container', 0, 'EXEMPT: decorative hairline'),
]

STATUS_TOKENS = Path(__file__).resolve().parent.parent / 'lib/config/depools_status_tokens.dart'
PAPER_TOKENS = Path(__file__).resolve().parent.parent / 'lib/config/depools_paper_tokens.dart'
OVERLAY_TOKENS = Path(__file__).resolve().parent.parent / 'lib/config/depools_overlay_tokens.dart'
CONTROL_TOKENS = Path(__file__).resolve().parent.parent / 'lib/config/depools_control_tokens.dart'
LOCATION_TOKENS = Path(__file__).resolve().parent.parent / 'lib/config/depools_location_tokens.dart'

# WCAG 1.4.11 asks 3:1 of a UI component's boundary. A switch has no text or icon to identify it,
# so unlike a labelled button its edge is the only thing that can carry that. The page-surface row
# is expected to fall short and is recorded as such: every switch in this app sits on a card, and
# this table is what would say so if one ever stopped doing that.
CONTROL_FLOOR = 3.0

# WCAG 1.4.11 asks 3:1 of a UI-component boundary. An overlay stroke's background is a
# photograph, so it has to clear that against EVERY possible background rather than against a
# known surface, which is why this is a floor over the whole luminance range rather than a pair.
OVERLAY_FLOOR = 3.0

# A location's hue is a GLYPH beside the name it belongs to, never text and never the only carrier
# of anything: the name is right there. So the requirement is WCAG 1.4.11's 3:1 for a meaningful
# graphic rather than the 4.5:1 the status solids hold, because those ARE read as text.
#
# Every hue clears 4.5 today regardless, the tightest being `red` on its own chip at 4.67. This is
# not an argument for raising the floor: it would then assert something WCAG does not, and the next
# hue that wants to look like the colour it is named after would hit a wall with no reason behind it.
LOCATION_FLOOR = 3.0

# **Contrast is the wrong instrument for a swatch, and this is the right one.** Two hues can each
# clear 4.5:1 against the card and still be the same colour to a user: the check above compares
# each hue to the BACKGROUND, and a picker asks the user to tell them apart from EACH OTHER. Apple's
# increased-contrast light values for yellow, orange and red all darken toward brown, so the warm
# end of the palette collapses in light mode while passing every contrast row.
#
# So this is CIEDE2000, a perceptual distance, and the threshold is calibrated against what was
# actually on screen rather than picked: amber against orange measured 9.2 in light and was
# indistinguishable, the same pair measured 13.3 in dark and was clearly a yellow beside an orange.
# The boundary is between those two, and 12 sits there. `orange` was removed rather than retuned,
# because retuning would mean inventing a value and every hue here is one of Apple's own.
HUE_SEPARATION_FLOOR = 12.0

# Ink read against paper, never against an app surface. The label preview renders a
# picture of a printed sheet, so both sides of every `dark:` pair hold the same hex
# and the only meaningful check is the one a reader performs: ink on white.
#
# `ink-subtle` is exempt for the same reason `border` is: it outlines an EMPTY cell so
# a user can see the page they are about to waste, and it carries no state.
PAPER_PAIRS = [
    ('text-ink', 'bg-paper', 4.5, ''),
    ('text-ink-muted', 'bg-paper', 4.5, ''),
    ('border-color-ink-subtle', 'bg-paper', 0, 'EXEMPT: empty-cell outline, carries no state'),
]


def parse_paper() -> dict[str, str]:
    """Read the print-surface supplement, keeping only the light value.

    Both sides of each pair are identical by construction; the parser asserts it
    rather than trusting it, because a drifted pair would mean a preview that
    changes with the app theme and stops matching print output.
    """
    values: dict[str, str] = {}
    pattern = re.compile(
        r"^\s*'([a-z-]+)':\s*'[a-z-]+\[(#[0-9A-Fa-f]{6})\]\s+dark:[a-z-]+\[(#[0-9A-Fa-f]{6})\]'")
    for line in PAPER_TOKENS.read_text().splitlines():
        if not (m := pattern.match(line)):
            continue
        key, light, dark = m.groups()
        if light.upper() != dark.upper():
            raise SystemExit(f'{key}: paper tokens must be identical in both appearances, '
                             f'got {light} and {dark}')
        values[key] = light
    return values


def parse_control() -> tuple[str, str]:
    """Read the control-edge supplement and return its (light, dark) pair."""
    pattern = re.compile(
        r"^\s*'border-color-control':\s*'border-\[(#[0-9A-Fa-f]{6})\]\s+"
        r"dark:border-\[(#[0-9A-Fa-f]{6})\]'")
    for line in CONTROL_TOKENS.read_text().splitlines():
        if m := pattern.match(line):
            return m.group(1), m.group(2)
    raise SystemExit('border-color-control not found in the control supplement')


def srgb_to_lab(value: str) -> tuple[float, float, float]:
    """CIELAB under D65, the space CIEDE2000 is defined in."""
    r, g, b = (int(value[i:i + 2], 16) / 255 for i in (1, 3, 5))

    def linear(c: float) -> float:
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4

    r, g, b = linear(r), linear(g), linear(b)
    x = (r * 0.4124564 + g * 0.3575761 + b * 0.1804375) / 0.95047
    y = r * 0.2126729 + g * 0.7151522 + b * 0.0721750
    z = (r * 0.0193339 + g * 0.1191920 + b * 0.9503041) / 1.08883

    def f(v: float) -> float:
        return v ** (1 / 3) if v > 216 / 24389 else (841 / 108) * v + 4 / 29

    fx, fy, fz = f(x), f(y), f(z)
    return 116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz)


def ciede2000(one: str, two: str) -> float:
    """Perceptual distance between two hexes. Roughly: under 10 reads as the same colour."""
    l1, a1, b1 = srgb_to_lab(one)
    l2, a2, b2 = srgb_to_lab(two)
    c1, c2 = math.hypot(a1, b1), math.hypot(a2, b2)
    cb = (c1 + c2) / 2
    g = 0.5 * (1 - math.sqrt(cb ** 7 / (cb ** 7 + 25 ** 7))) if cb else 0.5
    a1p, a2p = (1 + g) * a1, (1 + g) * a2
    c1p, c2p = math.hypot(a1p, b1), math.hypot(a2p, b2)
    h1p = math.degrees(math.atan2(b1, a1p)) % 360 if (b1 or a1p) else 0.0
    h2p = math.degrees(math.atan2(b2, a2p)) % 360 if (b2 or a2p) else 0.0

    dlp, dcp = l2 - l1, c2p - c1p
    if c1p * c2p == 0:
        dhp = 0.0
    elif abs(h2p - h1p) <= 180:
        dhp = h2p - h1p
    else:
        dhp = h2p - h1p - 360 if h2p - h1p > 180 else h2p - h1p + 360
    dHp = 2 * math.sqrt(c1p * c2p) * math.sin(math.radians(dhp) / 2)

    lbp, cbp = (l1 + l2) / 2, (c1p + c2p) / 2
    if c1p * c2p == 0:
        hbp = h1p + h2p
    elif abs(h1p - h2p) <= 180:
        hbp = (h1p + h2p) / 2
    else:
        hbp = (h1p + h2p + 360) / 2 if h1p + h2p < 360 else (h1p + h2p - 360) / 2

    tt = (1 - 0.17 * math.cos(math.radians(hbp - 30))
          + 0.24 * math.cos(math.radians(2 * hbp))
          + 0.32 * math.cos(math.radians(3 * hbp + 6))
          - 0.20 * math.cos(math.radians(4 * hbp - 63)))
    sl = 1 + (0.015 * (lbp - 50) ** 2) / math.sqrt(20 + (lbp - 50) ** 2)
    sc = 1 + 0.045 * cbp
    sh = 1 + 0.015 * cbp * tt
    rt = -math.sin(math.radians(2 * 30 * math.exp(-(((hbp - 275) / 25) ** 2)))) * (
        2 * math.sqrt(cbp ** 7 / (cbp ** 7 + 25 ** 7)))

    return math.sqrt((dlp / sl) ** 2 + (dcp / sc) ** 2 + (dHp / sh) ** 2
                     + rt * (dcp / sc) * (dHp / sh))


def parse_families(source: Path = STATUS_TOKENS) -> dict[str, dict[str, tuple[str, str]]]:
    """Read a three-role supplement so it is checked from its real source.

    Returns {family: {role: (light, dark)}} where role is 'solid', 'soft' or
    'soft-foreground'. The status families and the location hues share this shape
    exactly, so they share the reader: a hue that forgets its soft pair is
    reported by the same missing-role check.
    """
    families: dict[str, dict[str, tuple[str, str]]] = {}
    pattern = re.compile(
        r"^\s*'(?:bg|text)-([a-z-]+?)(-soft-foreground|-soft)?':\s*"
        r"'(?:bg|text)-\[(#[0-9A-Fa-f]{6})\]\s+dark:(?:bg|text)-\[(#[0-9A-Fa-f]{6})\]'"
    )
    for line in source.read_text().splitlines():
        if not (m := pattern.match(line)):
            continue
        family, suffix, light, dark = m.groups()
        role = {None: 'solid', '-soft': 'soft', '-soft-foreground': 'soft-foreground'}[suffix]
        families.setdefault(family, {})[role] = (light, dark)
    return families


def check_overlay() -> tuple[str, str, float, float]:
    """Return the overlay pair and the worst background it can face.

    The overlay strokes do not sit on an app surface, so there is no pair to check. What has to
    hold is that for ANY background, at least one of the two strokes is legible against it.

    Contrast to the light stroke falls as the background brightens and contrast to the dark stroke
    rises, so the better of the two is worst exactly where the curves cross. Sweeping luminance
    finds that crossing without having to solve for it, and the result is the guarantee the two
    overlay screens rely on: it does not matter what the camera is pointed at.
    """
    pattern = re.compile(
        r"^\s*'([a-z-]+)':\s*'[a-z-]+\[(#[0-9A-Fa-f]{6})\]\s+dark:[a-z-]+\[(#[0-9A-Fa-f]{6})\]'")
    values: dict[str, str] = {}
    for line in OVERLAY_TOKENS.read_text().splitlines():
        if not (m := pattern.match(line)):
            continue
        key, light, dark = m.groups()
        if light.upper() != dark.upper():
            raise SystemExit(f'{key}: overlay tokens must be identical in both appearances, '
                             f'got {light} and {dark}')
        values[key] = light

    ink = values['border-color-overlay-ink']
    paper = values['border-color-overlay-paper']
    l_ink, l_paper = luminance(ink), luminance(paper)

    worst = 99.0
    worst_at = 0.0
    for i in range(0, 10001):
        bg = i / 10000
        better = max(
            (max(bg, l_ink) + 0.05) / (min(bg, l_ink) + 0.05),
            (max(bg, l_paper) + 0.05) / (min(bg, l_paper) + 0.05),
        )
        if better < worst:
            worst, worst_at = better, bg

    return ink, paper, worst, worst_at


def main() -> int:
    colors = parse_colors(DESIGN.read_text())
    failures: list[str] = []

    print(f"{'PAIR':<44}{'LIGHT':>8}{'':>4}{'DARK':>8}{'':>4}{'NEED':>6}")
    print('-' * 78)
    for fg, bg, need, note in PAIRS:
        if fg not in colors or bg not in colors:
            failures.append(f'missing token: {fg} or {bg}')
            continue
        rl = contrast(colors[fg]['light'], colors[bg]['light'])
        rd = contrast(colors[fg]['dark'], colors[bg]['dark'])
        if need == 0:
            mark_l = mark_d = ' exempt'
        else:
            mark_l = '   OK' if rl >= need else '  FAIL'
            mark_d = '   OK' if rd >= need else '  FAIL'
            if rl < need:
                failures.append(f'{fg}/{bg} light {rl:.2f} < {need}')
            if rd < need:
                failures.append(f'{fg}/{bg} dark {rd:.2f} < {need}')
        label = f'{fg} / {bg}'
        print(f'{label:<44}{rl:>8.2f}{mark_l:>4}{rd:>8.2f}{mark_d:>4}{need if need else "-":>6}')

    status = parse_families()

    print()
    print(f'STATUS SOLIDS on surface-container ({len(status)} families, parsed from '
          f'{STATUS_TOKENS.name})')
    print('-' * 78)
    for name, roles in status.items():
        light, dark = roles['solid']
        rl = contrast(light, colors['surface-container']['light'])
        rd = contrast(dark, colors['surface-container']['dark'])
        if rl < 4.5:
            failures.append(f'status {name} solid light {rl:.2f} < 4.5')
        if rd < 4.5:
            failures.append(f'status {name} solid dark {rd:.2f} < 4.5')
        print(f'{name:<44}{rl:>8.2f}{"   OK" if rl >= 4.5 else "  FAIL":>4}'
              f'{rd:>8.2f}{"   OK" if rd >= 4.5 else "  FAIL":>4}{4.5:>6}')

    print()
    print('STATUS BADGES: soft-foreground on its own soft background')
    print('-' * 78)
    for name, roles in status.items():
        if 'soft' not in roles or 'soft-foreground' not in roles:
            failures.append(f'status {name} is missing a soft or soft-foreground token')
            continue
        fg_l, fg_d = roles['soft-foreground']
        bg_l, bg_d = roles['soft']
        rl, rd = contrast(fg_l, bg_l), contrast(fg_d, bg_d)
        if rl < 4.5:
            failures.append(f'badge {name} light {rl:.2f} < 4.5')
        if rd < 4.5:
            failures.append(f'badge {name} dark {rd:.2f} < 4.5')
        print(f'{name + " badge":<44}{rl:>8.2f}{"   OK" if rl >= 4.5 else "  FAIL":>4}'
              f'{rd:>8.2f}{"   OK" if rd >= 4.5 else "  FAIL":>4}{4.5:>6}')

    location = parse_families(LOCATION_TOKENS)

    print()
    print(f'LOCATION HUES: the glyph on a card, and the tick on its own swatch '
          f'({len(location)} hues, parsed from {LOCATION_TOKENS.name})')
    print('-' * 78)
    for name, roles in sorted(location.items()):
        if 'solid' not in roles:
            failures.append(f'location {name} has no solid pair')
            continue
        light, dark = roles['solid']
        rl = contrast(light, colors['surface-container']['light'])
        rd = contrast(dark, colors['surface-container']['dark'])
        if rl < LOCATION_FLOOR:
            failures.append(f'location {name} glyph light {rl:.2f} < {LOCATION_FLOOR}')
        if rd < LOCATION_FLOOR:
            failures.append(f'location {name} glyph dark {rd:.2f} < {LOCATION_FLOOR}')
        print(f'{name + " glyph on card":<44}{rl:>8.2f}'
              f'{"   OK" if rl >= LOCATION_FLOOR else "  FAIL":>4}{rd:>8.2f}'
              f'{"   OK" if rd >= LOCATION_FLOOR else "  FAIL":>4}{LOCATION_FLOOR:>6}')

        # The form's chosen swatch draws a tick in `on-primary` over this same tone, and that
        # single alias has to land on all seven. It works because these fills follow the
        # primary's own brightness rule, dark in light mode and bright in dark, but "it works
        # because of a rule" is exactly the claim worth measuring rather than repeating.
        tl = contrast(colors['on-primary']['light'], light)
        td = contrast(colors['on-primary']['dark'], dark)
        if tl < 4.5:
            failures.append(f'location {name} tick light {tl:.2f} < 4.5')
        if td < 4.5:
            failures.append(f'location {name} tick dark {td:.2f} < 4.5')
        print(f'{name + " tick on its swatch":<44}{tl:>8.2f}'
              f'{"   OK" if tl >= 4.5 else "  FAIL":>4}{td:>8.2f}'
              f'{"   OK" if td >= 4.5 else "  FAIL":>4}{4.5:>6}')

    print()
    print('LOCATION HUES: told apart from EACH OTHER, CIEDE2000 over every pair, worst three')
    print('-' * 78)
    for idx, appearance in ((0, 'light'), (1, 'dark')):
        distances = sorted(
            (ciede2000(a['solid'][idx], b['solid'][idx]), n1, n2)
            for (n1, a), (n2, b) in itertools.combinations(sorted(location.items()), 2)
        )
        for d, n1, n2 in distances[:3]:
            if d < HUE_SEPARATION_FLOOR:
                failures.append(f'{n1} and {n2} are {d:.1f} apart in {appearance}, '
                                f'under {HUE_SEPARATION_FLOOR}')
            label = f'{n1} vs {n2} ({appearance})'
            mark = '   OK' if d >= HUE_SEPARATION_FLOOR else '  FAIL'
            print(f'{label:<44}{d:>8.1f}{mark:>4}{"":>8}{"":>4}{HUE_SEPARATION_FLOOR:>6}')

    paper = parse_paper()

    print()
    print(f'PAPER: ink read on paper, one fixed value per token (parsed from '
          f'{PAPER_TOKENS.name})')
    print('-' * 78)
    for fg, bg, need, note in PAPER_PAIRS:
        if fg not in paper or bg not in paper:
            failures.append(f'missing paper token: {fg} or {bg}')
            continue
        ratio = contrast(paper[fg], paper[bg])
        if need and ratio < need:
            failures.append(f'{fg}/{bg} {ratio:.2f} < {need}')
        mark = ' exempt' if not need else ('   OK' if ratio >= need else '  FAIL')
        label = f'{fg} / {bg}'
        print(f'{label:<44}{ratio:>8.2f}{mark:>4}{ratio:>8.2f}{mark:>4}'
              f'{need if need else "-":>6}')
        if note:
            print(f'  {note}')

    print()
    print(f'OVERLAY: two strokes over a photograph, worst case across every background '
          f'(parsed from {OVERLAY_TOKENS.name})')
    print('-' * 78)
    ink, paper_stroke, worst, worst_at = check_overlay()
    if worst < OVERLAY_FLOOR:
        failures.append(f'overlay pair {worst:.2f} < {OVERLAY_FLOOR} at background L={worst_at:.3f}')
    mark = '   OK' if worst >= OVERLAY_FLOOR else '  FAIL'
    print(f'{"ink " + ink + " + paper " + paper_stroke:<44}{worst:>8.2f}{mark:>4}'
          f'{worst:>8.2f}{mark:>4}{OVERLAY_FLOOR:>6}')
    print(f'  the better of the two strokes, at its worst background (L={worst_at:.3f})')

    print()
    print(f'CONTROL EDGE: a switch has no text to identify it, so its boundary carries 1.4.11 '
          f'(parsed from {CONTROL_TOKENS.name})')
    print('-' * 78)
    c_light, c_dark = parse_control()
    for surface, label in (('surface-container', 'on a card'), ('surface', 'on the page')):
        rl = contrast(c_light, colors[surface]['light'])
        rd = contrast(c_dark, colors[surface]['dark'])
        ok_l = rl >= CONTROL_FLOOR
        ok_d = rd >= CONTROL_FLOOR
        # The page row is expected to fall short and is not a failure: no switch in this app sits
        # on the page surface. It is printed so that stops being an assumption.
        gate = surface == 'surface-container'
        if gate and not (ok_l and ok_d):
            failures.append(
                f'border-color-control {label}: {rl:.2f} light / {rd:.2f} dark < {CONTROL_FLOOR}')
        m_l = '   OK' if ok_l else ('  FAIL' if gate else '  note')
        m_d = '   OK' if ok_d else ('  FAIL' if gate else '  note')
        print(f'{"border-color-control " + label:<44}{rl:>8.2f}{m_l:>4}{rd:>8.2f}{m_d:>4}'
              f'{CONTROL_FLOOR:>6}')
    print('  the page row is a note: every switch in this app sits on a card')

    print()
    if failures:
        print(f'{len(failures)} FAILURE(S):')
        for f in failures:
            print(f'  {f}')
        return 1
    print('All non-exempt pairs pass WCAG AA in both light and dark.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
